import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { gzipSync } from 'node:zlib';

const appRoot = resolve(import.meta.dirname, '..');
const backendRoot = resolve(appRoot, '..', 'backend');
const beach = [
  'beach-shack', 'beach-wooden-pier', 'beach-fishing-boat',
  'beach-lifeguard-tower', 'beach-chai-tapri', 'beach-maggi-stall',
  'beach-campfire', 'beach-signpost', 'beach-sun-lounger',
  'beach-umbrella', 'beach-palm-tree',
];
const names = {
  loft: ['loft16'],
  roof: ['school-rooftop'],
  tea: ['tea-ground', 'chai-stall', 'three-shops', 'barber-shop', 'dance-stage', 'maple-tree'],
  beach,
};
const packs = {};
const files = new Map();
for (const [room, models] of Object.entries(names)) {
  const filenames = [];
  for (const model of models) {
    filenames.push(`models/${model}.glb`, `textures/${model}.rgba`);
  }
  if (room === 'beach') filenames.push('textures/beach-sand.rgba', 'textures/beach-sand-normal.rgba', 'textures/beach-water-normal.rgba');
  packs[room] = filenames.map(name => `${name}.gz`);
  for (const name of filenames) {
    const source = join(appRoot, 'assets', name.startsWith('models/') ? 'runtime_models' : 'textures', name.split('/')[1]);
    if (!existsSync(source)) throw new Error(`Missing room asset: ${source}. Run npm run assets:prepare first.`);
    const bytes = readFileSync(source);
    const compressed = gzipSync(bytes, { level: 6 });
    files.set(`${name}.gz`, { compressed, size: compressed.length, originalSize: bytes.length,
      sha256: createHash('sha256').update(compressed).digest('hex') });
  }
}
const version = `v-${createHash('sha256').update(JSON.stringify([...files].map(([name, info]) => [name, info.sha256]))).digest('hex').slice(0, 16)}`;
const output = join(backendRoot, 'public', 'room-assets', version);
for (const [name, info] of files) {
  const destination = join(output, name);
  mkdirSync(dirname(destination), { recursive: true });
  if (!existsSync(destination)) writeFileSync(destination, info.compressed);
}
const manifest = {
  version,
  packs,
  files: Object.fromEntries([...files].map(([name, info]) => [name, { size: info.size, originalSize: info.originalSize, sha256: info.sha256 }])),
};
writeFileSync(join(appRoot, 'src', 'three', 'roomAssetManifest.ts'),
  `// Generated by scripts/prepare_room_assets.mjs. Do not edit by hand.\nexport const roomAssetManifest = ${JSON.stringify(manifest, null, 2)} as const;\n`);
writeFileSync(join(output, 'manifest.json'), JSON.stringify(manifest, null, 2));
for (const [room, filenames] of Object.entries(packs)) {
  const size = filenames.reduce((sum, name) => sum + files.get(name).size, 0);
  console.log(`${room}: ${filenames.length} files, ${(size / 1048576).toFixed(1)} MiB`);
}
console.log(`Room assets ready: ${output}`);
