import cors from 'cors';
import express from 'express';
import { toNodeHandler } from 'better-auth/node';
import { env } from './config/env.js';
import { auth } from './modules/auth/auth.js';
import { healthRoutes } from './modules/health/routes.js';
import { socialRoutes } from './modules/social/routes.js';
import { chatRoutes } from './modules/chat/routes.js';
import { publicSafetyRoutes } from './modules/safety/public-routes.js';

import path from 'node:path';
import { musicRoutes } from './modules/music/routes.js';

export const app = express();
// Nginx is the single trusted hop in front of this process. Use the original
// client address for authentication throttling and abuse controls.
app.set('trust proxy', 1);
const allowedOrigins = new Set(env.corsOrigins);

app.use(
  cors({
    origin: (origin, callback) => callback(null, !origin || allowedOrigins.has(origin)),
    credentials: true,
  }),
);

// Ensure mobile requests without Origin or with 'null' Origin inherit the trusted authUrl
app.use('/api/auth', (req, _res, next) => {
  if (!req.headers.origin || req.headers.origin === 'null') {
    req.headers.origin = env.authUrl;
  }
  next();
});

// Better Auth reads the raw request body, so mount it before express.json().
app.all('/api/auth/*', toNodeHandler(auth));
app.use(express.json({ limit: '2mb' }));
app.use(express.urlencoded({ extended: false, limit: '8kb' }));
app.use(publicSafetyRoutes);
// Immutable room files are generated by adda/scripts/prepare_room_assets.py.
// Serve them from object storage/CDN in production when download traffic grows.
app.use('/room-assets', express.static(path.join(process.cwd(), 'public/room-assets'), {
  immutable: true,
  maxAge: '1y',
  fallthrough: false,
}));
app.use('/music', express.static(path.join(process.cwd(), 'public/music')));
app.use('/api/health', healthRoutes);
app.use('/api/chat', chatRoutes);
app.use('/api/music', musicRoutes);
app.use('/api', socialRoutes);

app.use((_request, response) => {
  response.status(404).json({ error: 'Not found' });
});
